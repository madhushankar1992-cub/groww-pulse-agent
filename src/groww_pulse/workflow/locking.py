"""An OS lock releases automatically when an operator process dies."""

import os
from contextlib import contextmanager

from groww_pulse.errors import ErrorCode, PulseError


@contextmanager
def run_lock(directory, run_id):
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{run_id}.lock"
    with path.open("a+b") as handle:
        if path.stat().st_size == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            raise PulseError(ErrorCode.PUBLICATION_CONFLICT) from None
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == "nt":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
